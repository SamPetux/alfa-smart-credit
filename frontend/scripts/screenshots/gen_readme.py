def presence(rel):
    marks = []
    for (d, _, _, _), short in zip(DEVICES, SHORT):
        marks.append(short if (ROOT / d / f"{rel}.png").exists() else "·")
    return " ".join(marks)


def table(section, items, prefix):
    lines = [f"| Кадр | Что показывает | {' '.join(SHORT)} |", "|---|---|---|"]
    for name, text in items.items():
        rel = f"{prefix}/{name}"
        if not any((ROOT / d / f"{rel}.png").exists() for d, *_ in DEVICES):
            continue
        link = f"[`{name}`](desktop-1440x900/{rel}.png)" if (ROOT / "desktop-1440x900" / f"{rel}.png").exists() else f"`{name}`"
        lines.append(f"| {link} | {text} | {presence(rel)} |")
    return "\n".join(lines)


